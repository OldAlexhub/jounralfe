let dark = false;
let scale = 1;
let fontOverrides: Record<string, object> = {};

export function configureAppearance(
  preference: 'system' | 'light' | 'dark',
  fontScale: number,
  systemDark: boolean,
) {
  const nextDark =
    preference === 'dark' || (preference === 'system' && systemDark);
  const nextScale = Math.max(0.85, Math.min(1.5, fontScale));
  if (dark === nextDark && scale === nextScale) return;
  dark = nextDark;
  scale = nextScale;
  fontOverrides = Object.fromEntries(
    Object.entries(scalable).map(([key, value]) => [
      key,
      {
        ...(value.fontSize
          ? { fontSize: Math.round(value.fontSize * scale) }
          : {}),
        ...(value.lineHeight
          ? { lineHeight: Math.round(value.lineHeight * scale) }
          : {}),
      },
    ]),
  );
}

export const appearance = {
  isDark: () => dark,
  fontScale: () => scale,
  background: () => (dark ? '#0F1715' : '#F7F3EB'),
};

export const styles = new Proxy(lightStyles, {
  get(target, property: string) {
    return [
      target[property as keyof typeof target],
      dark && darkStyles[property as keyof typeof darkStyles],
      fontOverrides[property],
    ];
  },
}) as typeof lightStyles;
